"""Refresh pinned offline assets from npm; no Node runtime or frontend build required.

Package integrity is checked against npm's SHA512 integrity before extraction.
Only explicitly selected regular files are copied; archive paths are never extracted.
"""
import base64
import hashlib
import io
import json
import tarfile
import urllib.request
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'assets/web/vendor'
packages = {
    'mermaid': ('12.3.0', {'dist/mermaid.min.js': 'mermaid.js'}),
    'katex': ('0.19.1', {'dist/katex.min.js': 'katex.js', 'dist/katex.min.css': 'katex.css'}),
    '@highlightjs/cdn-assets': ('11.12.0', {'highlight.min.js': 'highlight.js', 'styles/github.min.css': 'highlight.css'}),
    'dompurify': ('3.4.18', {'dist/purify.min.js': 'purify.js'}),
}
manifest = []
root.mkdir(parents=True, exist_ok=True)
previous = json.loads((root/'manifest.json').read_text()) if (root/'manifest.json').exists() else []
for name, (version, files) in packages.items():
    with urllib.request.urlopen(f'https://registry.npmjs.org/{name}/{version}') as response:
        meta = json.load(response)
    with urllib.request.urlopen(meta['dist']['tarball']) as response:
        data = response.read()
    integrity = 'sha512-' + base64.b64encode(hashlib.sha512(data).digest()).decode()
    assert integrity == meta['dist']['integrity'], name
    locked = next((item for item in previous if item['package']==name and item['version']==version), None)
    if locked:
        assert integrity == locked['integrity'], f'Pinned integrity changed: {name}'
    copied = []
    with tarfile.open(fileobj=io.BytesIO(data), mode='r:gz') as archive:
        for member in archive.getmembers():
            path = member.name.removeprefix('package/')
            dest = files.get(path)
            if name == 'katex' and path.startswith('dist/fonts/') and path.endswith('.woff2'):
                dest = path.removeprefix('dist/')
            if path.lower() in ('license', 'license.md', 'license.txt'):
                dest = name.replace('/', '-') + '-LICENSE.txt'
            if dest and member.isfile():
                output = root / dest
                output.parent.mkdir(parents=True, exist_ok=True)
                content = archive.extractfile(member).read()
                output.write_bytes(content)
                copied.append({'path': dest, 'sha256': hashlib.sha256(content).hexdigest()})
    assert set(files.values()).issubset({f['path'] for f in copied}), (name, copied)
    manifest.append({'package': name, 'version': version, 'integrity': integrity, 'files': copied})
    print(name, version, len(copied))
(root / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
assets = root.parent
entries = []
for path in sorted(assets.rglob('*')):
    if path.is_file() and path.suffix in ('.js', '.css', '.woff2'):
        relative = path.relative_to(assets).as_posix()
        entries.append(f'        "{relative}" => Some(include_bytes!("{relative}").as_slice()),')
(assets / 'embedded.rs').write_text('// Generated by scripts/fetch-web-assets.py\nfn embedded_asset(path: &str) -> Option<&\'static [u8]> {\n    match path {\n' + '\n'.join(entries) + '\n        _ => None,\n    }\n}\n', encoding='utf-8')
